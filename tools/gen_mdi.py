#!/usr/bin/env python3
"""Generate MdiData.java: the vendored Material Design Icons font and its name table.

Plugin Java code cannot read the package's assets/ folder, so the font travels inside
the DEX as deflated, base64-encoded string chunks. MdiFont inflates it to the cache dir
on first use. Output goes to build/generated, never to src/.
"""
import base64
import hashlib
import re
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MDI = ROOT / 'third_party' / 'mdi'
OUT = ROOT / 'build' / 'generated'
PACKAGE = 'com.shymoose.ksnavbar'
# Class-file string constants are limited to 65535 bytes of modified UTF-8.
CHUNK = 60000


def icon_table(css: str):
    pairs = re.findall(r'\.mdi-([a-z0-9-]+)::before\s*\{\s*content:\s*"\\([0-9A-Fa-f]+)"', css)
    if len(pairs) < 5000:
        raise SystemExit(f'Expected thousands of MDI icons, found {len(pairs)}')
    return ''.join(f'{name}={code.upper()}\n' for name, code in pairs), len(pairs)


def chunks(data: bytes):
    text = base64.b64encode(zlib.compress(data, 9)).decode('ascii')
    return [text[i:i + CHUNK] for i in range(0, len(text), CHUNK)]


def java_array(name, parts):
    body = ',\n'.join(f'        "{part}"' for part in parts)
    return f'    static final String[] {name} = {{\n{body}\n    }};\n'


def generate():
    font = (MDI / 'materialdesignicons-webfont.ttf').read_bytes()
    table, count = icon_table((MDI / 'materialdesignicons.css').read_text(encoding='utf-8'))
    match = re.search(r'\?v=([0-9]+\.[0-9]+\.[0-9]+)', (MDI / 'materialdesignicons.css').read_text(encoding='utf-8')[:600])
    version = match.group(1) if match else 'unknown'
    digest = hashlib.sha256(font).hexdigest()[:16]
    source = (
        '// Generated by tools/gen_mdi.py. Do not edit.\n'
        f'package {PACKAGE};\n\n'
        'final class MdiData {\n'
        '    private MdiData() {}\n'
        f'    static final String VERSION = "{version}";\n'
        f'    /** Changes whenever the font bytes change, so the cached file is replaced. */\n'
        f'    static final String FONT_ID = "{digest}";\n'
        f'    static final int ICON_COUNT = {count};\n'
        + java_array('FONT', chunks(font))
        + '    /** Lines of name=HEXCODEPOINT. */\n'
        + java_array('NAMES', chunks(table.encode('ascii')))
        + '}\n'
    )
    target = OUT / Path(*PACKAGE.split('.')) / 'MdiData.java'
    target.parent.mkdir(parents=True, exist_ok=True)
    if not target.exists() or target.read_text(encoding='ascii') != source:
        target.write_text(source, encoding='ascii')
    return target, count, len(font)


if __name__ == '__main__':
    path, count, size = generate()
    print(f'{path}: {count} icons, font {size} bytes')
